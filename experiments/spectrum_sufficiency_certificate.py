"""Machine-checked ingredients for the hand proof of spectrum sufficiency at
(1,1) and (2,1), plus two exact structural laws that reframe the open problem.

Companion to docs/spectrum_sufficiency_proof.md (the human-readable proof).
Every finite check cited by that document is executed here; the script aborts
if any fails, so the proof's checkable claims cannot silently rot.

WHAT IS PROVEN (per cell, by Theorem 1 of the doc + these checks):
  Certificate schema: if L is a set of signatures with
    ING-1 (closure)  : C_L = {configs with signature in L} is forward-invariant,
    ING-2 (activity) : every member of C_L has an active cell,
  then every member of C_L persists. With
    ING-3 (complement): every configuration outside C_L dies,
  L exactly characterises persistence. ING-1..3 are verified here for
  (1,1) (L = 2 signatures, |C_L| = 24) and (2,1) (L = 7, |C_L| = 180) --
  and in fact for every tau_a >= tau_p cell tested.

STRUCTURAL LAWS (exhaustive, BOTH regimes -- these reframe the problem):

  P4 (dwell characterisation of death). A configuration persists IFF its
     trajectory never contains a step with TWO simultaneously dwelling cells
     (a dwelling cell = receptive now, still receptive next step). Exact at
     all 10 cells tested. Death is simultaneous waiting.

  P5 (signature kinematics). The signature changes only via dwell: with no
     dweller it is invariant (Lemma A), and each dwell at loop position k
     shifts only the two adjacent gaps (upstream +1, downstream -1, mod B)
     (Lemma B). Verified over every transition of every cell tested. So on
     never-2-dwell trajectories the signature performs single adjacent-gap
     exchanges -- and by P4 those are exactly the live trajectories.

  P6 (the regime, relocated). ING-1 and ING-2 hold at EVERY cell in BOTH
     regimes: the live configuration set is always forward-invariant and
     activity-supported. What fails at tau_p > tau_a is exactly ING-3,
     equivalently SIGNATURE-MEASURABILITY of the live set. The open problem
     is now: why is the basin boundary a union of signature classes exactly
     when the active band covers the passive band? By P4 this is: why is
     "eventually two simultaneous dwellers" signature-measurable iff
     tau_a >= tau_p?

  Also checked: at (1,1) each live class is a SINGLE orbit of the group
  generated by loop rotation and global clock-shift (12 = 4 x 3 members), but
  clock-shift does NOT commute with the step (state 0 is special), so the
  hand proof enumerates members rather than invoking equivariance. Recorded
  to preempt the tempting-but-wrong shortcut.

House Rules Compliance: exhaustive, deterministic, no RNG.
Output: result/topology/spectrum_sufficiency_certificate.npz.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
from itertools import product
from collections import defaultdict

ADJ2 = {0: (1, 2), 1: (0, 3), 2: (0, 3), 3: (1, 2)}
CYC = [0, 1, 3, 2]
CELLS = [(1, 1), (2, 1), (2, 2), (3, 1), (3, 2), (3, 3), (4, 3), (4, 4),
         (1, 2), (2, 3), (2, 4), (3, 4)]


def step2(cfg, ta, tp):
    S = ta + tp
    return tuple((1 if sum(1 <= cfg[j] <= ta for j in ADJ2[i]) >= 1 else 0)
                 if s == 0 else (s + 1) % (S + 1) for i, s in enumerate(cfg))


def sig(cfg, S):
    ph = [cfg[i] for i in CYC]
    return tuple(sorted((ph[(k + 1) % 4] - ph[k]) % (S + 1) for k in range(4)))


def fates(ta, tp):
    S = ta + tp
    fate = {}
    for c in product(range(S + 1), repeat=4):
        if c in fate:
            continue
        path, cur = [], c
        while cur not in fate and cur not in path:
            path.append(cur)
            cur = step2(cur, ta, tp)
        val = fate[cur] if cur in fate else any(
            any(x) for x in path[path.index(cur):])
        for p in path:
            fate[p] = val
    return fate


def audit(ta, tp):
    S = ta + tp
    B = S + 1
    fate = fates(ta, tp)

    # --- ING-1..3 and signature-measurability --------------------------------
    cls_fate = defaultdict(set)
    for c, f in fate.items():
        cls_fate[sig(c, S)].add(f)
    L = {s for s, f in cls_fate.items() if f == {True}}
    CL = [c for c in fate if sig(c, S) in L]
    ing1 = all(sig(step2(c, ta, tp), S) in L for c in CL)
    ing2 = all(any(1 <= x <= ta for x in c) for c in CL)
    ing3 = all(not fate[c] for c in fate if sig(c, S) not in L)
    measurable = all(len(f) == 1 for f in cls_fate.values())

    # live CONFIG set: invariance + activity (the universal halves of P6)
    live_cfg = [c for c, f in fate.items() if f]
    live_inv = all(fate[step2(c, ta, tp)] for c in live_cfg)
    live_act = all(any(1 <= x <= ta for x in c) for c in live_cfg)

    # --- P4: dwell characterisation ------------------------------------------
    p4_ok = True
    for c, f in fate.items():
        seen, cur, maxdw = set(), c, 0
        while cur not in seen:
            seen.add(cur)
            n = step2(cur, ta, tp)
            maxdw = max(maxdw, sum(1 for i in range(4)
                                   if cur[i] == 0 and n[i] == 0))
            cur = n
        if f != (maxdw <= 1):
            p4_ok = False
            break

    # --- P5: lemmas A and B ---------------------------------------------------
    p5_ok = True
    for c in fate:
        n = step2(c, ta, tp)
        ph0 = [c[i] for i in CYC]
        ph1 = [n[i] for i in CYC]
        adv = [0 if (c[CYC[k]] == 0 and n[CYC[k]] == 0) else 1 for k in range(4)]
        g0 = [(ph0[(k + 1) % 4] - ph0[k]) % B for k in range(4)]
        g1 = [(ph1[(k + 1) % 4] - ph1[k]) % B for k in range(4)]
        if [(g0[k] + adv[(k + 1) % 4] - adv[k]) % B for k in range(4)] != g1:
            p5_ok = False
            break

    return dict(ta=ta, tp=tp, n_L=len(L), n_CL=len(CL),
                ing1=ing1, ing2=ing2, ing3=ing3, measurable=measurable,
                live_inv=live_inv, live_act=live_act, p4=p4_ok, p5=p5_ok)


def orbit_check_11():
    """(1,1): each live class is one <rotation, clock-shift> orbit, yet
    clock-shift does not commute with the step. Both facts asserted."""
    ta, tp = 1, 1
    S = ta + tp
    B = S + 1
    fate = fates(ta, tp)

    def rot(c, r):
        ph = [c[i] for i in CYC]
        ph = ph[r:] + ph[:r]
        out = [0] * 4
        for k, i in enumerate(CYC):
            out[i] = ph[k]
        return tuple(out)

    def shift(c, d):
        return tuple((x + d) % B for x in c)

    for s_target in [(0, 1, 1, 1), (0, 2, 2, 2)]:
        members = {c for c in fate if sig(c, S) == s_target}
        seed = sorted(members)[0]
        orb, frontier = set(), [seed]
        while frontier:
            c = frontier.pop()
            if c in orb:
                continue
            orb.add(c)
            frontier += [rot(c, r) for r in range(4)]
            frontier += [shift(c, d) for d in range(B)]
        assert orb == members, f"(1,1) class {s_target} is not a single orbit"
        comm = all(step2(shift(c, d), ta, tp) == shift(step2(c, ta, tp), d)
                   for c in members for d in range(1, B))
        assert not comm, "clock-shift unexpectedly commutes -- doc is stale"
    return True


def main():
    print(f"{'(ta,tp)':>8} {'regime':>7} | {'|L|':>4} {'|C_L|':>6} "
          f"{'ING-1':>6} {'ING-2':>6} {'ING-3':>6} {'meas.':>6} | "
          f"{'liveinv':>7} {'liveact':>7} {'P4':>5} {'P5':>5}")
    recs = []
    for ta, tp in CELLS:
        r = audit(ta, tp)
        recs.append(r)
        regime = "ta>=tp" if ta >= tp else "ta<tp"
        print(f"{str((ta,tp)):>8} {regime:>7} | {r['n_L']:4d} {r['n_CL']:6d} "
              f"{str(r['ing1']):>6} {str(r['ing2']):>6} {str(r['ing3']):>6} "
              f"{str(r['measurable']):>6} | {str(r['live_inv']):>7} "
              f"{str(r['live_act']):>7} {str(r['p4']):>5} {str(r['p5']):>5}",
              flush=True)

    # the assertions the proof doc relies on
    for r in recs:
        cell = (r["ta"], r["tp"])
        assert r["ing1"] and r["ing2"], f"ING-1/2 failed at {cell} (universal)"
        assert r["live_inv"] and r["live_act"], f"live-set laws failed at {cell}"
        assert r["p4"], f"P4 dwell characterisation failed at {cell}"
        assert r["p5"], f"P5 signature kinematics failed at {cell}"
        want = r["ta"] >= r["tp"]
        assert r["ing3"] == want and r["measurable"] == want, \
            f"regime split changed at {cell}"
    by = {(r["ta"], r["tp"]): r for r in recs}
    assert (by[(1, 1)]["n_L"], by[(1, 1)]["n_CL"]) == (2, 24), "(1,1) L changed"
    assert (by[(2, 1)]["n_L"], by[(2, 1)]["n_CL"]) == (7, 180), "(2,1) L changed"
    orbit_check_11()
    print("\nall proof-cited checks pass (including (1,1) orbit structure and "
          "non-commutation)")

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "result", "topology", "spectrum_sufficiency_certificate.npz")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    np.savez(out, **{k: np.array([r[k] for r in recs]) for k in recs[0]})
    print(f"wrote {out}")


if __name__ == "__main__":
    main()

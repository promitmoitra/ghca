"""The discrete-calculus ladder: where between "relative phase only" and "full
absolute state" does persistence become decidable?

Follow-up to persistent_set_structure.py, prompted by the observation that the
gap field is a discrete-exterior-calculus object: it is the DISCRETE GRADIENT of
cell phase along the reentrant loop, its loop-sum is the DISCRETE CURL (equal to
(S+1) x the GGH winding number w, cf. topology_winding_capacity.py), and the
edge-difference at a cell is the DISCRETE DIVERGENCE (a phase Laplacian). Each
rung of that ladder is tested as a persistence invariant, exhaustively on the
2x2 core.

FINDINGS (every number generated by this script):

1. THE CURL IS WELL-DEFINED BUT INSUFFICIENT. The telescoping identity
   sum(gaps) = 0 mod (S+1) holds with zero violations everywhere, so the winding
   w is always defined. w = 0 is uniformly dead in every cell tested (the
   irrotational phase field cannot circulate), and the maximal w is uniformly
   alive where present -- but intermediate windings are MIXED at every
   (tau_a, tau_p) tested. The winding classifies which loops are alive on a
   RUNNING trajectory (PR #54's criterion); it under-determines which initial
   conditions get there. The gradient spectrum is strictly finer than the curl.

2. DIV-BASED REFINEMENTS DO NOT RESCUE tau_p > tau_a. Appending the sorted div
   spectrum, or rotation-canonicalising the aligned (gap, div) edge pairs,
   leaves impure classes at every failing cell (e.g. (2,3): 10 impure of 58 for
   the full canonical gap arrangement). Since div is derived from the gap field,
   the canonical arrangement subsumes every div-based invariant: THE ENTIRE
   RELATIVE-PHASE DESCRIPTION OF THE LOOP IS INSUFFICIENT when tau_p > tau_a.

3. THE SUFFICIENCY THRESHOLD IS LOCATED. The ladder, config-weighted
   (configurations lying in impure classes, monotone under refinement):

       (2,3), N=1296:  grad spectrum 432 -> grad arrangement 240
                       -> arrangement + active count 96
                       -> arrangement + ABSOLUTE STATE MULTISET 0   <- threshold
                       (canonical phases, the symmetry orbit: 0, by construction)

   Knowing HOW MANY cells are active is not enough; persistence at
   tau_p > tau_a requires knowing WHICH absolute states are present -- i.e. how
   deep into the refractory band each passive cell sits (its time-to-receptive).
   And the sufficient invariant is barely coarser than the symmetry orbit
   itself (330 vs 336 classes at (2,3); 1030 vs 1044 at (3,4)): compression
   collapses from ~50-160x (relative-only, tau_p <= tau_a) to ~4x. The
   tau_p <= tau_a boundary is therefore a genuine REGIME CHANGE in description
   complexity, not a technicality of one signature.

4. CORRECTION to persistent_set_structure.md Section 5. That doc rejected the
   "sorted type pattern" augmentation with the argument that it "is not a
   refinement at all" because impure CLASS COUNTS rose. The argument was wrong:
   appending data to a signature always refines the partition (same augmented
   class => same base class), and an impure class count CAN rise under
   refinement -- one impure class splits into several. The metric that cannot
   rise is the number of CONFIGURATIONS in impure classes, which this script
   uses throughout (and which decreases monotonically down the ladder, as it
   must). The augmentation was a genuine refinement that was merely still
   insufficient. Section 5 is corrected in the same commit as this file.

House Rules Compliance:
    - Deterministic and exhaustive; no RNG anywhere.
    - Substrate/analysis boundary: dynamics identical to the validated
      companion experiments; every invariant here is an analysis construct.
Output: result/topology/persistent_set_dec.npz + a printed doc table.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
from itertools import product
from collections import defaultdict

ADJ2 = {0: (1, 2), 1: (0, 3), 2: (0, 3), 3: (1, 2)}
CYC = [0, 1, 3, 2]
FAIL_CELLS = [(1, 2), (2, 3), (2, 4), (3, 4)]
CONTROL_CELLS = [(2, 2), (3, 3)]
CURL_CELLS = [(1, 1), (2, 2), (3, 2), (3, 3)]


def step2(cfg, ta, tp):
    S = ta + tp
    return tuple((1 if sum(1 <= cfg[j] <= ta for j in ADJ2[i]) >= 1 else 0)
                 if s == 0 else (s + 1) % (S + 1) for i, s in enumerate(cfg))


def persists2(cfg, ta, tp):
    seen, cur = {}, cfg
    while cur not in seen:
        seen[cur] = len(seen)
        cur = step2(cur, ta, tp)
    return any(any(x) for c, t in seen.items() if t >= seen[cur] for x in [c])


def gapfield(cfg, S):
    ph = [cfg[i] for i in CYC]
    return [(ph[(k + 1) % 4] - ph[k]) % (S + 1) for k in range(4)]


# --- the ladder, coarsest to finest -----------------------------------------
def inv_spectrum(cfg, S, ta):
    return tuple(sorted(gapfield(cfg, S)))


def inv_arrangement(cfg, S, ta):
    g = gapfield(cfg, S)
    return min(tuple(g[(k + r) % 4] for k in range(4)) for r in range(4))


def inv_arr_act(cfg, S, ta):
    return (inv_arrangement(cfg, S, ta), sum(1 <= x <= ta for x in cfg))


def inv_arr_states(cfg, S, ta):
    return (inv_arrangement(cfg, S, ta), tuple(sorted(cfg)))


def inv_canonical(cfg, S, ta):
    ph = [cfg[i] for i in CYC]
    return min(tuple(ph[(k + r) % 4] for k in range(4)) for r in range(4))


def inv_div(cfg, S, ta):
    g = gapfield(cfg, S)
    d = tuple(sorted(g[k] - g[(k - 1) % 4] for k in range(4)))
    return (inv_spectrum(cfg, S, ta), d)


LADDER = [("grad_spectrum", inv_spectrum),
          ("spectrum_plus_div", inv_div),
          ("grad_arrangement", inv_arrangement),
          ("arrangement_act", inv_arr_act),
          ("arrangement_states", inv_arr_states),
          ("canonical_phases", inv_canonical)]


def audit(fn, ta, tp):
    """(n_classes, n_impure_classes, n_configs_in_impure_classes)."""
    S = ta + tp
    cls = defaultdict(list)
    for c in product(range(S + 1), repeat=4):
        cls[fn(c, S, ta)].append(persists2(c, ta, tp))
    imp = [v for v in cls.values() if len(set(v)) > 1]
    return len(cls), len(imp), sum(len(v) for v in imp)


def curl_audit(ta, tp):
    """Telescoping violations, and fate-mixedness per winding number."""
    S = ta + tp
    viol, byw = 0, defaultdict(set)
    for c in product(range(S + 1), repeat=4):
        g = gapfield(c, S)
        if sum(g) % (S + 1) != 0:
            viol += 1
        byw[sum(g) // (S + 1)].add(persists2(c, ta, tp))
    mixed = sorted(w for w, f in byw.items() if len(f) > 1)
    dead0 = byw.get(0) == {False}
    return viol, sorted(byw), mixed, dead0


def main():
    print("=== curl (winding) audit ===")
    curl_rows = []
    for ta, tp in CURL_CELLS:
        viol, ws, mixed, dead0 = curl_audit(ta, tp)
        curl_rows.append(dict(ta=ta, tp=tp, violations=viol,
                              mixed_windings=len(mixed), w0_dead=dead0))
        print(f"({ta},{tp}): telescoping violations={viol}, windings={ws}, "
              f"mixed={mixed}, w=0 uniformly dead={dead0}")

    print("\n=== the ladder at the failing (tau_p > tau_a) cells ===")
    recs = []
    for ta, tp in FAIL_CELLS + CONTROL_CELLS:
        S = ta + tp
        N = (S + 1) ** 4
        role = "control" if (ta, tp) in CONTROL_CELLS else "failing"
        print(f"\n({ta},{tp})  N={N}  [{role}]")
        print(f"  {'invariant':>20} {'classes':>8} {'impure':>7} {'cfgs-impure':>12}")
        prev = None
        for name, fn in LADDER:
            ng, ni, nc = audit(fn, ta, tp)
            if prev is not None and nc > prev:
                raise RuntimeError(f"refinement increased config-weighted "
                                   f"impurity at ({ta},{tp}) {name}")
            # div sits off the main chain; only enforce monotonicity on the chain
            if name != "spectrum_plus_div":
                prev = nc
            recs.append(dict(ta=ta, tp=tp, inv=name, n_classes=ng,
                             n_impure=ni, cfgs_impure=nc, role=role))
            print(f"  {name:>20} {ng:8d} {ni:7d} {nc:12d}", flush=True)

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "result", "topology", "persistent_set_dec.npz")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    np.savez(out,
             ta=np.array([r["ta"] for r in recs]),
             tp=np.array([r["tp"] for r in recs]),
             inv=np.array([r["inv"] for r in recs]),
             n_classes=np.array([r["n_classes"] for r in recs]),
             n_impure=np.array([r["n_impure"] for r in recs]),
             cfgs_impure=np.array([r["cfgs_impure"] for r in recs]),
             role=np.array([r["role"] for r in recs]),
             curl_ta=np.array([r["ta"] for r in curl_rows]),
             curl_tp=np.array([r["tp"] for r in curl_rows]),
             curl_violations=np.array([r["violations"] for r in curl_rows]),
             curl_mixed=np.array([r["mixed_windings"] for r in curl_rows]),
             curl_w0_dead=np.array([r["w0_dead"] for r in curl_rows]))
    print(f"\nwrote {out}")

    print("\n--- results-doc table (generated; do not hand-type) ---")
    print("| cell | invariant | classes | impure classes | configs in impure |")
    print("| :---: | :--- | ---: | ---: | ---: |")
    for r in recs:
        if r["role"] == "failing":
            print(f"| ({r['ta']}, {r['tp']}) | `{r['inv']}` | {r['n_classes']} | "
                  f"{r['n_impure']} | {r['cfgs_impure']} |")

    thr = [r for r in recs if r["inv"] == "arrangement_states"]
    print(f"\nsufficiency threshold (arrangement+states) exact at all failing "
          f"cells: {all(r['cfgs_impure'] == 0 for r in thr if r['role']=='failing')}")
    for a, b in [("arrangement_states", "canonical_phases")]:
        ra = {(r['ta'], r['tp']): r['n_classes'] for r in recs if r['inv'] == a}
        rb = {(r['ta'], r['tp']): r['n_classes'] for r in recs if r['inv'] == b}
        print(f"threshold vs symmetry-orbit class counts: "
              f"{[(k, ra[k], rb[k]) for k in sorted(ra) if k in rb]}")


if __name__ == "__main__":
    main()

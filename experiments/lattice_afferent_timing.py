"""Fixing Negative 2 — can a recurrent medium learn a timescale without teaching itself?

`docs/lattice_timescale_notes.md` found that on a 2-D excitable lattice the
input-timing τ rule **locks and then stops tracking**: once τ settles, the medium
sustains reentrant waves at period ≈ τ, so each cell's input is generated by its
neighbours at interval ≈ τ and the rule sits at a self-confirming fixed point. The
e10 lesson ("teach τ from external input, not self-timing") returns in a harder form,
because on a recurrent medium the network's own activity is indistinguishable from
external input at the single-cell level.

This tests the diagnosis directly. Every cell now senses **two** input streams:

  * **afferent** — a weak global rhythmic timing signal at the drive period, which the
    cell can *sense* but which is subthreshold on its own (it does not fire the cell).
    Biologically this is a modulatory/thalamic-style afferent carrying timing rather
    than drive; formally it is the exogenous channel the pool implicitly had.
  * **lateral** — neighbour excitation, which is what actually propagates waves. This
    is the endogenous stream that carries the medium's *own* rhythm.

Sparse pacemaker sites still inject real excitation so waves exist. The rhythm is
therefore available both exogenously (afferent) and endogenously (via waves), and the
only thing that varies between conditions is **which stream the τ rule learns from**:

  all         — every input edge (afferent OR lateral): the failure mode
  afferent    — afferent edges only: the hypothesised fix
  quiet-gated — every input edge, but plasticity gated on LOW local activity (a proxy
                for "this input is probably exogenous", requiring no labelled channel —
                the harder, more interesting version)
  own         — the e10 self-firing rule (ratchet control)

Protocol: drive period 6 → 18 → 6. A rule that genuinely tracks exogenous timing
should follow all three phases; the self-confirming one stays pinned.
"""

import os
import sys
import json
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import ghca_stats as st  # noqa: E402

L = int(os.environ.get("AFF_L", "96"))
PHASE = int(os.environ.get("AFF_PHASE", "2500"))
N_SEEDS = int(os.environ.get("AFF_N", "5"))
SCHEDULE = [(6, PHASE), (18, PHASE), (6, PHASE)]
ACT, THETA = 2, 1.0
TMIN, TMAX = 3.0, 34.0
ETA = 0.15
N_PACE = int(os.environ.get("AFF_PACE", "36"))
QUIET_Q = float(os.environ.get("AFF_QUIET", "0.35"))   # gate: local activity percentile
RULES = ("all", "afferent", "quiet-gated", "own")
OUT = os.path.join(ROOT, "result", "stats")
os.makedirs(OUT, exist_ok=True)


def nbr_count(a):
    return (np.roll(a, 1, 0) + np.roll(a, -1, 0)
            + np.roll(a, 1, 1) + np.roll(a, -1, 1)).astype(np.float32)


def run(rule, seed):
    rng = np.random.default_rng(seed)
    phi = np.zeros((L, L), np.int32)
    tau = rng.uniform(TMIN, TMAX, (L, L)).astype(np.float32)
    pm = np.zeros(L * L, bool)
    pm[rng.choice(L * L, N_PACE, replace=False)] = True
    pm = pm.reshape(L, L)

    last_ev = np.full((L, L), -1.0, np.float32)
    last_fire = np.full((L, L), -1.0, np.float32)
    prev_supra = np.zeros((L, L), bool)
    prev_aff = np.zeros((L, L), bool)
    act_ema = np.zeros((L, L), np.float32)          # local activity estimate for gating
    traj, t = [], 0

    for P, dur in SCHEDULE:
        tau[pm] = P                                 # pacemakers keep the imposed period
        for _ in range(dur):
            active = (phi >= 1) & (phi <= ACT)
            rested = phi == 0
            nbr = nbr_count(active)

            # exogenous afferent: a global timing pulse every cell senses. Subthreshold
            # by construction — it never appears in `excite`, so it carries timing only.
            afferent = np.zeros((L, L), bool)
            if t % P == 0:
                afferent[:] = True
            # pacemakers additionally receive real (suprathreshold) drive, so waves exist
            pace_drive = pm & afferent

            lateral_supra = nbr >= THETA
            excite = rested & (lateral_supra | pace_drive)

            # rising edges of each stream
            lat_edge = lateral_supra & ~prev_supra
            aff_edge = afferent & ~prev_aff
            prev_supra, prev_aff = lateral_supra, afferent

            # advance clocks, wrap on per-cell tau, then apply excitation
            moving = phi >= 1
            phi[moving] += 1
            phi[phi > np.ceil(tau).astype(np.int32)] = 0
            phi[excite] = 1

            # local activity estimate (for the quiet gate) — a cheap leaky average of
            # neighbourhood activity, computable locally in a shader
            act_ema = 0.9 * act_ema + 0.1 * nbr_count(active)

            # ---- select the stream the rule learns from ----
            if rule == "own":
                ev = (phi == 1) & ~pm
                prev = last_fire
            else:
                if rule == "afferent":
                    ev = aff_edge & ~pm
                elif rule == "quiet-gated":
                    thr = np.quantile(act_ema, QUIET_Q)
                    ev = (lat_edge | aff_edge) & ~pm & (act_ema <= thr)
                else:                               # "all"
                    ev = (lat_edge | aff_edge) & ~pm
                prev = last_ev

            seen = ev & (prev >= 0)
            if seen.any():
                dt = np.clip((t - prev[seen]).astype(np.float32), 0, 60.0)
                tau[seen] = np.clip(tau[seen] + ETA * (dt - tau[seen]), TMIN, TMAX)
            if rule == "own":
                last_fire[ev] = t
            else:
                last_ev[ev] = t

            if t % 100 == 0:
                free = ~pm
                traj.append((t, P, float(tau[free].mean()),
                             float(np.abs(tau[free] - P).mean())))
            t += 1
    return tau, pm, traj


def phase_error(traj):
    """Mean |τ − P| over the last 40% of each phase (after transients)."""
    out = []
    n = len(traj) // len(SCHEDULE)
    for i in range(len(SCHEDULE)):
        seg = traj[i * n:(i + 1) * n]
        tail = seg[int(0.6 * len(seg)):]
        out.append(float(np.mean([e for (_, _, _, e) in tail])))
    return out


def main():
    res = {}
    for rule in RULES:
        errs = np.zeros((N_SEEDS, len(SCHEDULE)))
        taus = np.zeros((N_SEEDS, len(SCHEDULE)))
        tau0 = None
        for s in range(N_SEEDS):
            tau, pm, traj = run(rule, s)
            errs[s] = phase_error(traj)
            n = len(traj) // len(SCHEDULE)
            for i in range(len(SCHEDULE)):
                seg = traj[i * n:(i + 1) * n]
                tail = seg[int(0.6 * len(seg)):]
                taus[s, i] = float(np.mean([m for (_, _, m, _) in tail]))
            if s == 0:
                tau0 = tau.copy()
        res[rule] = {"err": errs, "tau": taus, "tau0": tau0}
        pm_str = "  ".join(f"P={P}: τ={taus[:, i].mean():5.1f} |τ−P|={errs[:, i].mean():5.1f}"
                           for i, (P, _) in enumerate(SCHEDULE))
        m, lo, hi = st.bootstrap_ci(errs[:, 1])          # the re-tune phase
        print(f"{rule:12s} {pm_str}   [re-tune |τ−P| {m:.1f} ({lo:.1f},{hi:.1f})]",
              flush=True)

    np.savez(os.path.join(OUT, "lattice_afferent_timing.npz"), L=L, phase=PHASE,
             n=N_SEEDS, schedule=np.array([P for P, _ in SCHEDULE]),
             **{f"{r}_{k}": res[r][k] for r in res for k in res[r]})
    with open(os.path.join(OUT, "lattice_afferent_timing.json"), "w") as f:
        json.dump({"L": L, "n": N_SEEDS, "schedule": [P for P, _ in SCHEDULE],
                   "rows": {r: {"tau": res[r]["tau"].mean(0).tolist(),
                                "err": res[r]["err"].mean(0).tolist()} for r in res}},
                  f, indent=2)
    print("\nwrote lattice_afferent_timing.{npz,json}", flush=True)


if __name__ == "__main__":
    main()
